/**
 * Build both halves of the plugin.
 *
 * - `lib/index.js` is the Host half: ESM for Node, with schemastery resolved
 *   from the installed dependency (the harness supplies the same schema
 *   library, so the Config stays a real schemastery schema).
 * - `lib/client.js` is the browser half in the Harness module-loader format:
 *   a lazy factory that receives `require` and returns `{ inject, apply }`.
 *   React stays external and comes from the page's shared module table.
 *
 * The script drives the esbuild CLI instead of its JS API so it also runs in
 * restricted environments where a child process may not use piped stdio.
 */
import { spawnSync } from 'node:child_process'
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const esbuild = join(root, 'node_modules', 'esbuild', 'bin', 'esbuild')
const banner = '/* Generated by scripts/build.mjs. Do not edit. */'

/**
 * Run the esbuild CLI with inherited stdio.
 * @param {string[]} args - CLI arguments.
 */
function runEsbuild(args) {
  const result = spawnSync(process.execPath, [esbuild, ...args], {
    cwd: root,
    stdio: 'inherit',
  })
  if (result.error) throw result.error
  if (result.status !== 0) throw new Error(`esbuild exited with ${String(result.status)}`)
}

async function buildHost() {
  runEsbuild([
    'src/host/index.ts',
    '--bundle',
    '--outfile=lib/index.js',
    '--platform=node',
    '--format=esm',
    '--target=node20',
    `--banner:js=${banner}`,
    '--log-level=warning',
  ])
}

async function buildClient() {
  const bodyPath = join(root, 'build/client-body.cjs')
  runEsbuild([
    'src/client/index.tsx',
    '--bundle',
    `--outfile=${bodyPath}`,
    '--platform=browser',
    '--format=cjs',
    '--target=es2020',
    '--jsx=automatic',
    '--external:react',
    '--external:react/jsx-runtime',
    `--banner:js=${banner}`,
    '--log-level=warning',
  ])
  const body = await readFile(bodyPath, 'utf8')
  const wrapped = `${banner}
window.__ModuleLoader__.load({
  id: 'deepseek-gruvbox-themes',
  factory(require) {
    const module = { exports: {} };
    const exports = module.exports;
${body}
    return module.exports;
  },
});
`
  await writeFile(join(root, 'lib/client.js'), wrapped)
  await rm(bodyPath, { force: true })
}

await rm(join(root, 'lib'), { recursive: true, force: true })
await rm(join(root, 'build'), { recursive: true, force: true })
await mkdir(join(root, 'lib'), { recursive: true })
await mkdir(join(root, 'build'), { recursive: true })
await buildHost()
await buildClient()
console.log('built lib/index.js and lib/client.js')
